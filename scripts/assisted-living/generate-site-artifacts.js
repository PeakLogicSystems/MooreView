#!/usr/bin/env node
'use strict';

/**
 * Generate assisted-living campus site artifacts:
 *   public/samples/assisted-living-site-config.js  (3D viewer import)
 *   public/samples/assisted-living-site-ortho.dxf  (orthographic site plan)
 *   samples/* (mirrored copies)
 *
 * Usage: node scripts/assisted-living/generate-site-artifacts.js [--rooms 200]
 */

const fs = require('fs');
const path = require('path');
const { parseTotalRooms } = require('./facility-config');
const { buildSiteLayout } = require('./alf-site-layout');

const ROOT = path.resolve(__dirname, '..', '..');
const OUT_DIRS = [
  path.join(ROOT, 'public', 'samples'),
  path.join(ROOT, 'samples'),
];

function dxfNum(n) {
  return Number(n).toFixed(4);
}

function rectPolyline(layer, x, y, w, h, closed = true) {
  const lines = [
    '0', 'LWPOLYLINE', '8', layer, '90', '4', '70', closed ? '1' : '0',
    '10', dxfNum(x), '20', dxfNum(y),
    '10', dxfNum(x + w), '20', dxfNum(y),
    '10', dxfNum(x + w), '20', dxfNum(y + h),
    '10', dxfNum(x), '20', dxfNum(y + h),
  ];
  return lines;
}

function dxfText(layer, x, y, height, text) {
  return [
    '0', 'TEXT', '8', layer,
    '10', dxfNum(x), '20', dxfNum(y),
    '40', dxfNum(height), '1', String(text).slice(0, 80),
  ];
}

/** Top-down site plan in meters (+X east, +Y north). Main tower centered at origin. */
function buildSiteDxf(site) {
  const { building: b, pool, villas, sitePad } = site;
  const lines = [
    '0', 'SECTION', '2', 'HEADER', '0', 'ENDSEC',
    '0', 'SECTION', '2', 'TABLES',
    '0', 'TABLE', '2', 'LAYER', '70', '6',
    '0', 'LAYER', '2', 'SITE', '70', '0', '62', '8', '6', 'CONTINUOUS',
    '0', 'LAYER', '2', 'BUILDING', '70', '0', '62', '5', '6', 'CONTINUOUS',
    '0', 'LAYER', '2', 'VILLA', '70', '0', '62', '3', '6', 'CONTINUOUS',
    '0', 'LAYER', '2', 'POOL', '70', '0', '62', '4', '6', 'CONTINUOUS',
    '0', 'LAYER', '2', 'ANNOTATIONS', '70', '0', '62', '7', '6', 'CONTINUOUS',
    '0', 'ENDTAB', '0', 'ENDSEC',
    '0', 'SECTION', '2', 'ENTITIES',
  ];

  const padX = -sitePad.w / 2;
  const padY = -sitePad.d / 2 - b.oz;
  lines.push(...rectPolyline('SITE', padX, padY, sitePad.w, sitePad.d));

  const towerX = -b.slabW / 2;
  const towerY = -b.slabD / 2 + b.oz;
  lines.push(...rectPolyline('BUILDING', towerX, towerY, b.slabW, b.slabD));
  lines.push(...dxfText('ANNOTATIONS', 0, towerY + b.slabD + 3, 3,
    `Main tower ${site.totalRooms} rooms (${site.roomsOnFloor.join('+')}/floor)`));

  for (const v of villas) {
    const vx = v.center.x - v.footprint.w / 2;
    const vy = v.center.z - v.footprint.d / 2;
    lines.push(...rectPolyline('VILLA', vx, vy, v.footprint.w, v.footprint.d));
    lines.push(...dxfText('ANNOTATIONS', v.center.x, vy + v.footprint.d + 2, 2.5,
      `${v.name} (${v.roomRange})`));
  }

  const px = pool.x - pool.w / 2;
  const py = pool.z - pool.d / 2;
  lines.push(...rectPolyline('POOL', px, py, pool.w, pool.d));
  lines.push(...dxfText('ANNOTATIONS', pool.x, py + pool.d + 2, 2.5, 'Therapy pool (exterior)'));

  lines.push(
    '0', 'TEXT', '8', 'ANNOTATIONS',
    '10', dxfNum(-sitePad.w / 2 + 4), '20', dxfNum(padY + sitePad.d - 6),
    '40', '4', '1', `Assisted Living campus — ${site.totalResidentialUnits} units`,
  );

  lines.push('0', 'ENDSEC', '0', 'EOF');
  return `${lines.join('\n')}\n`;
}

function buildSiteConfigJs(site) {
  return `// Generated by scripts/assisted-living/generate-site-artifacts.js — do not edit.
export const SITE = ${JSON.stringify(site, null, 2)};
`;
}

function writeToOutDirs(filename, content) {
  for (const dir of OUT_DIRS) {
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, filename), content, 'utf8');
  }
}

function syncOrtho3dHtml() {
  const src = path.join(ROOT, 'samples', 'assisted-living-ortho-3d.html');
  const dst = path.join(ROOT, 'public', 'samples', 'assisted-living-ortho-3d.html');
  if (!fs.existsSync(src)) return;
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.copyFileSync(src, dst);
}

function main() {
  const totalRooms = parseTotalRooms();
  const site = buildSiteLayout(totalRooms);
  writeToOutDirs('assisted-living-site-config.js', buildSiteConfigJs(site));
  writeToOutDirs('assisted-living-site-ortho.dxf', buildSiteDxf(site));
  syncOrtho3dHtml();
  console.log('Assisted-living site artifacts generated:');
  console.log(`  Main tower: ${site.totalRooms} rooms (${site.roomsOnFloor.join('+')}/floor)`);
  console.log(`  Villas: ${site.villas.length} × ${site.villas[0]?.unitCount || 25} = ${site.totalVillaUnits} units`);
  console.log(`  Total residential: ${site.totalResidentialUnits}`);
  console.log('  public/samples/assisted-living-site-config.js');
  console.log('  public/samples/assisted-living-site-ortho.dxf');
  console.log('  3D viewer: /samples/assisted-living-ortho-3d.html');
}

main();
